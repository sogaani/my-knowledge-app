/** Regenerate every Gold markdown file from the index. Gold is derived; never hand-edited. */
export function buildGold(cfg: KbConfig, db: Database): string[] {
  const written: string[] = [];
  const out = (rel: string, text: string) => {
    const abs = join(cfg.gold, rel);
    mkdirSync(join(abs, ".."), { recursive: true });
    // links are written relative to 300_gold/ (`link()`); a page in a subfolder (304_books/index.md) needs one more `../`
    const depth = rel.split("/").length - 1;
    const body = depth ? text.replace(/\]\(\.\.\//g, `](${"../".repeat(depth + 1)}`) : text;
    writeFileSync(abs, `<!-- generated by kb build ${today()} — do not edit; change Silver and rerun -->\n${body.trimEnd()}\n`);
    written.push(`${GOLD_PREFIX}${rel}`);
  };
  const q = (filters: string, extra: Partial<Parameters<typeof runQuery>[1]> = {}) =>
    runQuery(db, { filters: parse(filters), limit: 10000, ...extra });

  // 302 subscriptions
  const subs = q("type=subscription");
  const active = subs.filter((s) => s.status === "active");
  const monthly = monthlyByCurrency(active); // per currency: yen and dollars are not added together
  out(GOLD.subscriptions, [
    "# サブスクリプション", "",
    `- 有効: ${active.length} 件 / 月額換算 **${formatTotals(monthly)}** / 年額換算 ${formatTotals(monthly, 12)}`, "",
    "| サービス | プラン | 料金 | 周期 | 次回更新 | 状態 |", "|---|---|---|---|---|---|",
    ...subs.sort((a, b) => String(a.fm.next_renewal ?? "9").localeCompare(String(b.fm.next_renewal ?? "9")))
      .map((s) => `| ${link(s)} | ${s.fm.plan ?? ""} | ${money(s.fm)} | ${s.fm.cycle ?? ""} | ${s.fm.next_renewal ?? ""} | ${s.status} |`),
    "", renewalWarnings(active),
  ].join("\n"));

  // 303 finance
  const accts = q("type=finance_account");
  out(GOLD.finance, [
    "# 金融サービス", "",
    "| 機関 | 種別 | 用途 | 制度 | 見直し予定 | 状態 |", "|---|---|---|---|---|---|",
    ...accts.map((a) => `| ${link(a)} | ${a.fm.kind ?? ""} | ${a.fm.purpose ?? ""} | ${a.fm.tax_scheme ?? ""} | ${a.fm.review_due ?? ""} | ${a.status} |`),
    "", "## 月次台帳", "",
    "| 月 | 合計 | 状態 | 要約 |", "|---|---|---|---|",
    ...q("type=ledger").sort((a, b) => String(b.fm.month ?? "").localeCompare(String(a.fm.month ?? "")))
      .map((l) => `| ${link(l)} | ¥${Math.round(Number(l.fm.total ?? 0)).toLocaleString()} | ${l.status} | ${l.summary ?? ""} |`),
  ].join("\n"));

  // 304 books: a read book is dated by finished_at, else purchased_at (bulk-imported books only know when they were bought)
  const books = q("type=book");
  const byStatus = group(books, (b) => b.status);
  const read = (byStatus.read ?? []).sort((a, b) => bookDate(b.fm).localeCompare(bookDate(a.fm)) || a.title.localeCompare(b.title, "ja"));
  const unrated = unratedImported(read);
  out(`${GOLD.books}/index.md`, [
    "# 読書", "",
    `- 読了 ${read.length} / 読書中 ${byStatus.reading?.length ?? 0} / 積読 ${byStatus.want?.length ?? 0}`,
    `- 未評価の読了本（取り込み分）: ${unrated.length} 冊`, "",
    "## 読書中", ...list(byStatus.reading ?? []),
    "", "## 読みたい", ...list(byStatus.want ?? []),
    "", "## 未評価の読了本", "",
    "一括取り込み（`imported: true`）で `rating` の無い読了本。購入日の古い順に 5 冊。週次の `review` が「今週評価する本」に挙げ、評価と 1 行の summary は `log-book` で付ける。", "",
    ...(unrated.length ? unrated.slice(0, 5).map((b) => `- ${link(b)} — ${b.fm.author ?? ""}${b.fm.purchased_at ? `（${b.fm.purchased_at} 購入）` : ""}`) : ["- （なし）"]),
    ...(unrated.length > 5 ? [`- …他 ${unrated.length - 5} 冊（\`kb query type=book status=read imported=true rating= --order purchased_at\`）`] : []),
    "", "## 読了（新しい順）", "", "| 書名 | 著者 | ジャンル | 評価 | 読了日 | 購入日 |", "|---|---|---|---|---|---|",
    ...read.map((b) => `| ${link(b)} | ${b.fm.author ?? ""} | ${b.fm.genre ?? ""}${b.fm.subgenre ? "/" + b.fm.subgenre : ""} | ${stars(b.fm.rating)} | ${b.fm.finished_at ?? ""} | ${b.fm.purchased_at ?? ""} |`),
  ].join("\n"));
  for (const [year, items] of Object.entries(group(read, (b) => bookYear(b.fm)))) {
    out(`${GOLD.books}/${year}.md`, [`# 読書 ${year}`, "", `- ${items.length} 冊${year === "unknown" ? "（読了日も購入日も無い本）" : ""}`, "", ...list(items.sort(byRating))].join("\n"));
  }

  // 305 media
  const media = q("type=media", { orderBy: "-watched_at" });
  const mByStatus = group(media, (m) => m.status);
  out(`${GOLD.media}/index.md`, [
    "# 映画・ドラマ", "",
    "## 視聴中", ...list(mByStatus.watching ?? []),
    "", "## 観たい", ...list(mByStatus.want ?? []),
    "", "## 視聴済み（新しい順）", "", "| 作品 | 種別 | 配信 | 評価 | 視聴日 |", "|---|---|---|---|---|",
    ...(mByStatus.watched ?? []).map((m) => `| ${link(m)} | ${m.fm.kind ?? ""} | ${m.fm.platform ?? ""} | ${stars(m.fm.rating)} | ${m.fm.watched_at ?? ""} |`),
  ].join("\n"));

  // 306 projects (plaintext): work projects live in 207_work (encrypted), so only their count appears here
  const allProjects = q("type=project");
  const projects = allProjects.filter((p) => !isEncryptedPath(p.path));
  const workActive = allProjects.filter((p) => isEncryptedPath(p.path) && p.status === "active").length;
  const pBy = group(projects, (p) => p.status);
  out(GOLD.projects, [
    "# プロジェクト", "",
    `- 仕事（207_work、暗号化）: 進行中 ${workActive} 件 — 内容はここに載せない`, "",
    "## 進行中", "", "| プロジェクト | 領域 | 期限 | 要約 |", "|---|---|---|---|",
    ...(pBy.active ?? []).map((p) => `| ${link(p)} | ${p.fm.area ?? ""} | ${p.fm.due ?? ""} | ${p.summary} |`),
    "", "## アイデア", ...list(pBy.idea ?? []),
    "", "## 一時停止", ...list(pBy.paused ?? []),
  ].join("\n"));

  // 301 learning
  const learning = q("type=learning");
  out(`${GOLD.learning}/index.md`, [
    "# 学習", "",
    "| トピック | レベル | 状態 | 最終復習 | 要約 |", "|---|---|---|---|---|",
    ...learning.map((l) => `| ${link(l)} | ${l.fm.level ?? ""} | ${l.status} | ${l.fm.last_reviewed ?? ""} | ${l.summary} |`),
  ].join("\n"));

  // 307 suggestions: the current `recommendation` note (208_reviews) and its reaction counts; the list itself stays in Silver
  out(GOLD.suggestions, suggestionsGold(cfg, db));

  // 300 market: catalyst calendar + stock / theme lists (200_market is not encrypted: no amounts or quantities here)
  {
    const stocks = q("type=stock").filter((n) => n.status !== "dropped");
    const themes = q("type=theme").filter((n) => n.status !== "closed");
    const day = (d: string) => Math.round((new Date(d).getTime() - new Date(today()).getTime()) / 86400000);
    const ev: { date: string; who: string; label: string; days: number }[] = [];
    const push = (n: QueryResult, date: unknown, label: string) => {
      const d = String(date ?? "");
      if (/^\d{4}-\d{2}-\d{2}$/.test(d)) ev.push({ date: d, who: link(n), label, days: day(d) });
    };
    for (const n of stocks) {
      const events = (Array.isArray(n.fm.events) ? n.fm.events : []) as { date?: string; label?: string }[];
      // next_earnings only adds a row when no event already sits on that date (the skill usually records both)
      if (!events.some((e) => e.date === n.fm.next_earnings)) push(n, n.fm.next_earnings, "決算発表");
      for (const e of events) push(n, e.date, String(e.label ?? ""));
    }
    for (const n of themes) for (const e of (Array.isArray(n.fm.events) ? n.fm.events : []) as { date?: string; label?: string }[]) push(n, e.date, String(e.label ?? ""));
    const upcoming = ev.filter((e) => e.days >= -7 && e.days <= 42).sort((a, b) => a.date.localeCompare(b.date));
    const codeOf = (n: QueryResult) => String(n.fm.code ?? "");
    const byStatus = group(stocks, (n) => n.status);
    const themesOf = stockThemes(stocks, themes);
    const stockRows = (xs: QueryResult[]) => xs.sort((a, b) => codeOf(a).localeCompare(codeOf(b))).map((n) =>
      `| ${codeOf(n)} | ${link(n)} | ${n.fm.market ?? ""} | ${n.fm.sector ?? ""} | ${(themesOf.get(n.path) ?? []).map((t) => link(t)).join("、")} | ${n.fm.next_earnings ?? ""} | ${n.fm.thesis ?? n.summary} |`);
    out(GOLD.market, [
      "# 市場メモ", "",
      "銘柄ノート（`stock`）とテーマノート（`theme`）の入口。`market-scan` が週次で更新し、`trade-plan` が毎朝読む。", "",
      "## カタリスト・カレンダー（過去 1 週間〜今後 6 週間）", "",
      "| 日付 | あと | 銘柄 / テーマ | 内容 |", "|---|---|---|---|",
      ...(upcoming.length ? upcoming.map((e) => `| ${e.date} | ${e.days < 0 ? `${-e.days} 日前` : e.days === 0 ? "今日" : `${e.days} 日`} | ${e.who} | ${e.label} |`) : ["| | | （なし） | |"]),
      "", "## 保有銘柄", "",
      "| コード | 銘柄 | 市場 | セクター | テーマ | 次回決算 | 論拠 |", "|---|---|---|---|---|---|---|",
      ...(stockRows(byStatus.holding ?? []).length ? stockRows(byStatus.holding ?? []) : ["| | （なし） | | | | | |"]),
      "", "## 監視銘柄", "",
      "| コード | 銘柄 | 市場 | セクター | テーマ | 次回決算 | 論拠 |", "|---|---|---|---|---|---|---|",
      ...(stockRows(byStatus.watch ?? []).length ? stockRows(byStatus.watch ?? []) : ["| | （なし） | | | | | |"]),
      "", "## テーマ", "",
      "| テーマ | 段階 | 状態 | 関連銘柄 | 要約 |", "|---|---|---|---|---|",
      ...(themes.length ? themes.map((n) => `| ${link(n)} | ${n.fm.stage ?? ""} | ${n.status} | ${(Array.isArray(n.fm.tickers) ? n.fm.tickers : []).join(", ")} | ${n.summary} |`) : ["| （なし） | | | | |"]),
    ].join("\n"));
  }

  // 308 trading: latest trade_plan sheet + index of recent sheets + portfolio snapshot (git-crypt encrypted in the data repo)
  const plans = q("type=trade_plan", { orderBy: "-date", limit: 30 });
  const ports = q("type=portfolio");
  if (!plans.length && !ports.length) out(GOLD.trading, "# 売買実行シート\n\n（`trade-plan` スキルがここを更新します。保有資産は楽天証券の資産残高 CSV を投げ込むと `portfolio` ノートになります）\n");
  else {
    const latest = plans[0];
    const sides = (n: QueryResult) => {
      const os = Array.isArray(n.fm.orders) ? (n.fm.orders as { side?: string }[]) : [];
      return { buy: os.filter((o) => o.side === "buy" || o.side === "add").length, sell: os.filter((o) => o.side === "sell" || o.side === "trim").length };
    };
    const latestBody = latest ? inlineBody(readNote(cfg, join(cfg.root, latest.path))?.body ?? "", latest.path) : "";
    out(GOLD.trading, [
      `# 売買実行シート${latest ? `（${latest.fm.date ?? latest.updated} 更新）` : ""}`, "",
      ...(latest ? [`> 元ノート: ${link(latest)} — 状態: ${latest.status}`, "", latestBody.trim(), ""] : ["（まだシートがありません。`trade-plan` を実行すると作られます）", ""]),
      "## 直近のシート", "",
      "| 日付 | 状態 | 買 | 売 | 要約 |", "|---|---|---|---|---|",
      ...plans.map((n) => { const s = sides(n); return `| ${link(n)} | ${n.status} | ${s.buy} | ${s.sell} | ${n.summary} |`; }),
      "", "## 保有資産", "",
      ...(ports.length
        ? ports.map((n) => `- ${link(n)} — ${n.fm.as_of ?? ""} 時点 / 評価額 ¥${Number(n.fm.total_value ?? 0).toLocaleString()} / 現物余力 ¥${Number(n.fm.buying_power ?? 0).toLocaleString()} / 株式 ${n.fm.positions ?? 0} 銘柄`)
        : ["- （なし）楽天証券の資産残高 CSV を投げ込むと作られます"]),
    ].join("\n"));
  }

  // 310 health: monthly health_log notes (git-crypt encrypted in the data repo, like 302/303/308)
  const logs = q("type=health_log", { orderBy: "-month" });
  const hm = (v: unknown) => (typeof v === "number" ? `${Math.floor(v / 60)}h${String(v % 60).padStart(2, "0")}m` : "-");
  out(GOLD.health, [
    "# 健康記録", "",
    "Google Health から `bun run collect` → `kb health import` で月ごとの `health_log` に集計。", "",
    "| 月 | 日数 | 平均歩数 | 平均睡眠 | ノート |", "|---|---|---|---|---|",
    ...(logs.length ? logs.map((n) => `| ${n.fm.month ?? ""} | ${n.fm.days ?? "-"} | ${typeof n.fm.avg_steps === "number" ? n.fm.avg_steps.toLocaleString("ja-JP") : "-"} | ${hm(n.fm.avg_sleep_min)} | ${link(n)} |`) : ["| （なし） | | | | |"]),
  ].join("\n"));

  // 311 location: monthly location_log notes (git-crypt encrypted in the data repo)
  const locs = q("type=location_log", { orderBy: "-month" });
  out(GOLD.location, [
    "# 滞在記録", "",
    "Google マップのタイムライン（`000_inbox` に置いたエクスポート）→ `kb location import` で月ごとの `location_log` に集計。", "",
    "| 月 | 滞在 | 場所数 | よく行った場所 | ノート |", "|---|---|---|---|---|",
    ...(locs.length
      ? locs.map((n) => `| ${n.fm.month ?? ""} | ${n.fm.visits ?? "-"} | ${n.fm.places ?? "-"} | ${(Array.isArray(n.fm.top_places) ? n.fm.top_places.slice(0, 3).join("、") : "").replace(/\|/g, "\\|")} | ${link(n)} |`)
      : ["| （なし） | | | | |"]),
  ].join("\n"));

  // 390 / 391 / 392: views across domains (views.ts)
  buildCrossViews(cfg, db, out, { daily: GOLD.daily, trends: GOLD.trends, upcoming: GOLD.upcoming });
  // 393: what to look at again today (resurface.ts). Plaintext, so encrypted domains are counted, not named.
  const again = resurface(db, today());
  out(GOLD.resurface, renderResurface(again));

  // 300 home
  const reviews = q("type=review", { orderBy: "-updated", limit: 5 });
  // recent: plaintext notes only; encrypted domains (git-crypt) appear as per-domain counts so their titles / summaries stay out of this plaintext file
  const silverByUpdated = runQuery(db, { filters: [], orderBy: "-updated", limit: 10000 }).filter((n) => !n.path.startsWith(GOLD_PREFIX));
  const recent = silverByUpdated.filter((n) => !isEncryptedPath(n.path)).slice(0, 15);
  const since = recent.at(-1)?.updated ?? "";
  const encryptedRecent = countByDomain(silverByUpdated.filter((n) => isEncryptedPath(n.path) && n.updated >= since));
  out(GOLD.home, [
    "# ホーム", "",
    "読む順番: このページ → `kb query` → 該当ノート。Bronze は `kb source <id>`。", "",
    "## ダッシュボード",
    `- [ライフログ](${GOLD.daily}) — 直近 60 日を 1 日 1 行で`,
    `- [トレンド](${GOLD.trends}) — 月ごとの推移`,
    `- [これからの予定](${GOLD.upcoming}) — 90 日先までの予定・期限`,
    `- [サブスクリプション](${GOLD.subscriptions}) — 月額換算 ${formatTotals(monthly)}`,
    `- [金融サービス](${GOLD.finance})`,
    `- [読書](${GOLD.books}/index.md) — 読了 ${byStatus.read?.length ?? 0}, 読書中 ${byStatus.reading?.length ?? 0}`,
    `- [映画・ドラマ](${GOLD.media}/index.md) — 視聴済み ${mByStatus.watched?.length ?? 0}`,
    `- [プロジェクト](${GOLD.projects}) — 進行中 ${pBy.active?.length ?? 0}${workActive ? `（仕事 ${workActive}）` : ""}`,
    `- [学習](${GOLD.learning}/index.md)`,
    `- [おすすめ](${GOLD.suggestions})`,
    `- [売買シート](${GOLD.trading})${plans.length ? ` — 最新 ${plans[0].fm.date ?? plans[0].updated}` : ""}`,
    `- [市場メモ](${GOLD.market}) — 銘柄・テーマ・カタリスト`,
    `- [健康記録](${GOLD.health})`,
    `- [滞在記録](${GOLD.location})`, "",
    ...renderResurfaceHome(again, GOLD.resurface), "",
    "## 最近のレビュー", ...list(reviews), "",
    "## 最近更新したノート", "", "| 更新 | type | ノート | 要約 |", "|---|---|---|---|",
    ...recent.map((n) => `| ${n.updated} | ${n.type} | ${link(n)} | ${n.summary} |`),
    "", `暗号化ドメインの更新${since ? `（${since} 以降）` : ""}: ${encryptedRecent.length ? encryptedRecent.map(([d, c]) => `${d} ${c} 件`).join("、") : "なし"} — 内容は 302/303/308/310/311 と 39x を参照`,
    "", `## 件数`, ...countsByType(db),
  ].join("\n"));

  // remove stale generated year files not rewritten this run
  for (const sub of [GOLD.books]) {
    const dir = join(cfg.gold, sub);
    if (!existsSync(dir)) continue;
    for (const f of readdirSync(dir)) {
      const rel = `${GOLD_PREFIX}${sub}/${f}`;
      if (f.endsWith(".md") && !written.includes(rel)) unlinkSync(join(dir, f));
    }
  }
  return written;
}

/**
 * Stock → theme notes, derived from the theme side: a theme lists its stocks in `tickers` (the only place the link is
 * maintained), so a stock belongs to every theme whose tickers contain its code. A stock's own `themes` (theme titles)
 * still counts, for a link no theme note carries. Silver is never rewritten: Gold shows the result.
 */
export function stockThemes(stocks: QueryResult[], themes: QueryResult[]): Map<string, QueryResult[]> {
  const byTitle = new Map(themes.map((t) => [t.title, t]));
  const byCode = new Map<string, QueryResult[]>();
  for (const t of themes) for (const c of (Array.isArray(t.fm.tickers) ? t.fm.tickers : []).map(String)) byCode.set(c, [...(byCode.get(c) ?? []), t]);
  const out = new Map<string, QueryResult[]>();
  for (const s of stocks) {
    const own = (Array.isArray(s.fm.themes) ? s.fm.themes : []).map((x) => byTitle.get(String(x))).filter((t): t is QueryResult => !!t);
    const all = [...new Set([...(byCode.get(String(s.fm.code ?? "")) ?? []), ...own])].sort((a, b) => a.title.localeCompare(b.title, "ja"));
    if (all.length) out.set(s.path, all);
  }
  return out;
}

/**
 * 307: entry to the suggestions. The `recommend` skill writes `recommendation` notes in Silver and the WebUI marks the
 * reactions there; this page links the current (open) note with per-section counts and lists the earlier ones.
 */
export function suggestionsGold(cfg: KbConfig, db: Database): string {
  const current = currentRecommendation(db);
  const all = runQuery(db, { filters: [{ field: "type", op: "=", value: RECOMMENDATION_TYPE }], orderBy: "-date", limit: 50 })
    .sort((a, b) => String(b.fm.date ?? "").localeCompare(String(a.fm.date ?? "")) || b.updated.localeCompare(a.updated));
  const lines = ["# おすすめ", "", "`recommend` スキルが 208_reviews の `recommendation` ノートに書き、WebUI の「おすすめ」タブがそれを表示して反応（読む / 興味なし）を記録する。ここは入口だけ。", ""];
  if (!current) lines.push("（まだ提案がありません。`recommend` を実行すると作られます）");
  else {
    const counts = suggestionCounts(parseSuggestions(readSuggestionBody(cfg, current.path)));
    lines.push(`## 最新: ${link(current)}（${current.fm.date ?? current.updated}）`, "", ...(current.summary ? [current.summary, ""] : []),
      "| 区分 | 提案 | 読む・観る | 興味なし | 未反応 |", "|---|---|---|---|---|",
      ...(counts.length ? counts.map((c) => `| ${c.section} | ${c.total} | ${c.read} | ${c.dismissed} | ${c.open} |`) : ["| （なし） | | | | |"]));
  }
  const past = all.filter((n) => n.path !== current?.path);
  if (past.length) lines.push("", "## 過去の一覧", "", ...past.map((n) => `- ${link(n)}（${n.fm.date ?? n.updated}、${n.status}）${n.summary ? " — " + n.summary : ""}`));
  return lines.join("\n");
}

/** Inline a Silver note body into Gold: drop its H1 and rebase relative .md links from the note's folder to 300_gold/. */
function inlineBody(body: string, notePath: string): string {
  const dir = posix.dirname(notePath);
  return body.replace(/^\s*# .*\n/, "").replace(/\]\((?!https?:|mailto:|#)([^)\s]+\.md)\)/g, (_, href: string) => `](../${posix.normalize(posix.join(dir, href))})`);
}
function parse(s: string) {
  return s.split(/\s+/).filter(Boolean).map((t) => {
    const [field, value] = t.split("=");
    return { field, op: "=" as const, value };
  });
}
function link(n: QueryResult): string {
  const p = n.path.endsWith("/README.md") ? n.path.slice(0, -"/README.md".length) + "/README.md" : n.path;
  return `[${n.title}](../${p})`;
}
function list(items: QueryResult[]): string[] {
  return items.length ? items.map((n) => `- ${link(n)}${n.summary && n.summary !== IMPORTED_SUMMARY ? " — " + n.summary : ""}`) : ["- （なし）"];
}
function group<T>(items: T[], key: (t: T) => string): Record<string, T[]> {
  const out: Record<string, T[]> = {};
  for (const i of items) (out[key(i)] ??= []).push(i);
  return out;
}
function stars(r: unknown): string {
  const n = Number(r);
  return Number.isFinite(n) && n > 0 ? "★".repeat(n) + "☆".repeat(5 - n) : "";
}
function byRating(a: QueryResult, b: QueryResult) {
  return Number(b.fm.rating ?? 0) - Number(a.fm.rating ?? 0);
}
function money(fm: Record<string, unknown>): string {
  const p = Number(fm.price ?? 0);
  return p ? formatMoney(p, currencyOf(fm)) : "";
}
function renewalWarnings(active: QueryResult[]): string {
  const soon = active.filter((s) => {
    const d = String(s.fm.next_renewal ?? "");
    if (!d) return false;
    const days = (new Date(d).getTime() - Date.now()) / 86400000;
    return days <= 30;
  });
  return soon.length ? "## 30 日以内に更新\n" + soon.map((s) => `- ${link(s)}: ${s.fm.next_renewal}`).join("\n") : "";
}
/** [domain, count] pairs for notes in encrypted domains, in domain order. */
function countByDomain(notes: QueryResult[]): [string, number][] {
  const c = new Map<string, number>();
  for (const n of notes) {
    const d = encryptedDomainOf(n.path);
    if (d) c.set(d, (c.get(d) ?? 0) + 1);
  }
  return [...c.entries()].sort(([a], [b]) => a.localeCompare(b));
}
